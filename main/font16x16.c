#define FONT16X16_COUNT (sizeof(hz16) / sizeof(hz16[0]))

// 通过汉字名称（UTF-8）检索字模数据
const GBK16_FontTypeDef* font16x16_get_by_name(const char *name)
{
    for (int i = 0; i < FONT16X16_COUNT; i++) {
        if (strcmp(hz16[i].ChnName, name) == 0) {
            return &hz16[i];
        }
    }
    return NULL;
}
